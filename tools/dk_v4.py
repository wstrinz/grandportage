#!/usr/bin/env python3
"""DK V4 slice for the census profile (docs/DK-V4-DESIGN.md): statement author and untrusted proposer.

The statement's meaning is what GP evaluates. This tool only writes it down: the predicate below
renders DK's (n_4) axioms and fences (`av4.validate_n4`, `av4.necessary_conditions` with Theorem A)
in the census formula language, with action atoms `act g x y` (map g in 0, 1, 2 for s1, s2, s3).
`difftest` checks GP's membership verdicts against DK's Python, structure by structure.

The proposer side (n = 19 listing, n = 23 catalogs) is untrusted: GP re-checks every member, every
canonical form and the LRAT refutation of the CNF Lean emits. A missed model leaves that CNF
satisfiable, so the claim is refused, never wrongly held.

DK's code and type files are read from the private harvest (corpus/harvest/dk-v4, git-ignored).
"""
