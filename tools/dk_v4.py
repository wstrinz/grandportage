def dk():
    """DK's audit-lane modules (untrusted; used to propose and as the differential oracle)."""
    sys.path.insert(0, str(AUDIT))
    import av4, fastcanon, small_control  # noqa: E401
    return av4, fastcanon, small_control


# --- the predicate ------------------------------------------------------------------------------

def adj(x, y): return {"adj": [x, y]}
def col(x, c): return {"color": [x, c]}
def act(g, x, y): return {"act": [g, x, y]}
def neg(f): return {"not": f}
def conj(*fs): return {"and": list(fs)}
def disj(*fs): return {"or": list(fs)}
def ex(x, f): return {"exists": x, "body": f}
def fa(x, f): return {"forall": x, "body": f}
def implies(a, b): return disj(neg(a), b)
def at_least(m, x, f): return {"atLeast": m, "var": x, "body": f}
def exactly(m, x, f): return conj(at_least(m, x, f), neg(at_least(m + 1, x, f)))

IDX = (0, 1, 2)                                  # s1, s2, s3
def fix(g, x): return act(g, x, x)
def full(x): return conj(*(fix(g, x) for g in IDX))                  # stabiliser V4
def free(x): return conj(*(neg(fix(g, x)) for g in IDX))             # stabiliser 1
def st(i, x): return conj(*(fix(g, x) if g == i else neg(fix(g, x)) for g in IDX))   # stabiliser <s_i>
def pt(x): return col(x, 0)
def ln(x): return col(x, 1)


def predicate(bstar=None):
    """DK's candidate predicate. Normal form (points colour 0, lines colour 1, no edge within a side)
    and the point action are part of the statement itself; `bstar` fixes a cell's line inventory."""
    axidx = lambda i: ex("K", ex("p", conj(ln("K"), full("K"), adj("p", "K"), st(i, "p"))))   # axis holds a stab-i point
    vxidx = lambda i: ex("x", ex("L", conj(pt("x"), full("x"), adj("x", "L"), st(i, "L"))))   # vertex on a stab-i line
    parts = [
        # (n_4): 4 points per line, 4 lines per point, two points on at most one line (av4.validate_n4)
        fa("L", implies(ln("L"), exactly(4, "p", adj("p", "L")))),
        fa("p", implies(pt("p"), exactly(4, "L", adj("p", "L")))),
        fa("p", fa("q", implies(conj(pt("p"), pt("q"), neg({"eq": ["p", "q"]})),
                                neg(at_least(2, "L", conj(adj("p", "L"), adj("q", "L"))))))),
        # Theorem A: exactly one vertex (V4-fixed point) and one axis (V4-fixed line)
        exactly(1, "x", conj(pt("x"), full("x"))),
        exactly(1, "K", conj(ln("K"), full("K"))),
        # incidences: adjacency only joins a point to a line
        fa("p", fa("L", implies(adj("p", "L"), conj(
            # ABS_N5: a stab-i point never lies on a stab-j line, i != j
            *(neg(conj(st(i, "p"), st(j, "L"))) for i in IDX for j in IDX if i != j),
            neg(conj(free("p"), full("L"))),       # GEO: free points lie on no axis
            neg(conj(full("p"), free("L"))),       # GEO: a vertex lies on no free line
            neg(conj(full("p"), full("L"))))))),   # GEO: no vertex on an axis
        # GF1: a stab-i line carries at most one stab-i point
        fa("L", implies(ln("L"), conj(*(implies(st(i, "L"), neg(at_least(2, "p", conj(adj("p", "L"), st(i, "p")))))
                                        for i in IDX)))),
        # GF2: a stab-i point lies on at most one stab-i line
        fa("p", implies(pt("p"), conj(*(implies(st(i, "p"), neg(at_least(2, "L", conj(adj("p", "L"), st(i, "L")))))
                                        for i in IDX)))),
        # the axis's point row is ALL stab-m points of ONE index m (axis unique by Theorem A)
        *(neg(conj(axidx(i), axidx(j))) for i in IDX for j in IDX if i < j),
        *(implies(axidx(i), fa("q", implies(conj(pt("q"), st(i, "q")),
                                            ex("K", conj(ln("K"), full("K"), adj("q", "K")))))) for i in IDX),
        # the vertex's pencil holds ALL stab-m lines of ONE index m (vertex unique by Theorem A)
        *(neg(conj(vxidx(i), vxidx(j))) for i in IDX for j in IDX if i < j),
        *(implies(vxidx(i), fa("M", implies(conj(ln("M"), st(i, "M")),
                                            ex("x", conj(pt("x"), full("x"), adj("x", "M")))))) for i in IDX),
        # Theorem A: the axis's index and the vertex's index agree
        *(neg(conj(axidx(i), vxidx(j))) for i in IDX for j in IDX if i != j),
    ]
    if bstar is not None:   # a cell: exactly 2 b*_i lines with stabiliser <s_i>
        parts += [exactly(2 * b, "L", conj(ln("L"), st(i, "L"))) for i, b in zip(IDX, bstar)]
    return conj(*parts)


def statement(pts, a0, count, bstar=None, catalog=None):
    s = {"colors": 2, "predicate": predicate(bstar), "kind": "V4_COUNT", "points": pts,
         "action": [list(a0[g]) for g in (1, 2, 3)], "count": count}
    if catalog is not None:
        s["assuming_complete"] = catalog
    return s


# --- objects ------------------------------------------------------------------------------------

def witness(pts, lines):
    """Points 0..pts-1, then line i as vertex pts+i."""
    return {"edges": sorted([p, pts + i] for i, l in enumerate(lines) for p in l), "colors": [0] * pts + [1] * len(lines)}


def action(pts, lines, perms):
    """DK's point action, extended to lines by the induced permutation (None if lines are not preserved)."""
    av4, _, _ = dk()
    fl = [frozenset(l) for l in lines]
    out = []
    for g in (1, 2, 3):
        lp = av4.induced_line_perm(fl, perms, g)
        if lp is None:
            return None
        out.append(list(perms[g][:pts]) + [pts + j for j in lp])
    return out


def rep(pts, lines, perms):
    a = action(pts, lines, perms)
    return None if a is None else {"witness": witness(pts, lines), "action": a}


def run(claims):
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "ledger.json"
        path.write_text(json.dumps({"claims": claims}), encoding="utf-8")
        out = subprocess.run([str(RUNNER), "run", str(path)], capture_output=True, text=True, encoding="utf-8")
    if out.returncode != 0:
        raise RuntimeError(out.stderr)
    return {c["key"]: c for c in json.loads(out.stdout)["claims"]}


def member_claims(pts, a0, bstar, structures, key0=1):
    """One COUNT-given-catalog-of-one claim per structure: held exactly when GP's memberB accepts it."""
    claims = []
    for t, (lines, perms) in enumerate(structures):
        r = rep(pts, lines, perms)
        if r is None:
            r = {"witness": witness(pts, lines), "action": [list(range(2 * pts))] * 3}
        s = statement(pts, a0, 1, bstar, catalog=[r["witness"]])
        claims.append(dict(s, key=key0 + t, scope=[2 * pts], certificate={"type": "v4catalog", "n": 2 * pts, "reps": [r]}))
    return claims


# --- n = 19 --------------------------------------------------------------------------------------

def n19_sys():
    _, _, sc = dk()
    return sc.Sys(19, [1, 1, 3], 3)


def enumerate_models(S, labels, fences=True, sort_lines=True, limit=None, seed=None):
    """All labelled normal-form models (pysat), as line lists. Untrusted: GP refutes the rest."""
    from pysat.formula import IDPool
    from pysat.card import CardEnc, EncType
    from pysat.solvers import Cadical195
    av4, _, _ = dk()
    n, P = S.n, S.perms
    R = range(n)
    pool = IDPool()
    x = lambda p, L: pool.id(("x", p, L))
    y = lambda g, L, M: pool.id(("y", g, L, M))
    cl = []

    def card(lits, k, kind):
        enc = (CardEnc.equals if kind == "eq" else CardEnc.atmost)(lits=lits, bound=k, vpool=pool,
                                                                    encoding=EncType.seqcounter)
        cl.extend(enc.clauses)

    def lexle(xs, ys, tag):
        e = [pool.id((tag, i)) for i in range(len(xs) + 1)]
        cl.append([e[0]])
        for i, (a, b) in enumerate(zip(xs, ys)):
            cl.extend([[-e[i + 1], e[i]], [-e[i + 1], -a, b], [-e[i + 1], a, -b], [e[i + 1], -e[i], -a, -b],
                       [e[i + 1], -e[i], a, b], [-e[i], -a, b]])

    for L in R: card([x(p, L) for p in R], 4, "eq")
    for p in R: card([x(p, L) for L in R], 4, "eq")
    for p, q in itertools.combinations(R, 2):
        zs = []
        for L in R:
            z = pool.id(("z", p, q, L)); zs.append(z)
            cl.extend([[-z, x(p, L)], [-z, x(q, L)], [z, -x(p, L), -x(q, L)]])
        card(zs, 1, "le")
    for g in (1, 2, 3):
        for L in R:
            card([y(g, L, M) for M in R], 1, "eq")
            card([y(g, M, L) for M in R], 1, "eq")
            for M in R:
                for p in R:
                    cl.append([-y(g, L, M), -x(p, L), x(P[g][p], M)])
    if sort_lines:
        for L in range(n - 1):
            lexle([x(p, L) for p in R], [x(p, L + 1) for p in R], ("col", L))
    for t, l in enumerate(labels):
        lexle([x(p, L) for p in R for L in R], [x(l[p], L) for p in R for L in R], ("lab", t))
    xs = [x(p, L) for p in R for L in R]
    out = []
    with Cadical195(bootstrap_with=cl) as s:
        if seed is not None:
            rnd = random.Random(seed)
        while s.solve(assumptions=[] if seed is None else [v if rnd.random() < 0.5 else -v for v in rnd.sample(xs, 8)]) \
                or (seed is not None and s.solve()):
            m = set(v for v in s.get_model() if v > 0)
            lines = [sorted(p for p in R if x(p, L) in m) for L in R]
            s.add_clause([-v if v in m else v for v in xs])
            if not fences or not av4.necessary_conditions(n, [frozenset(l) for l in lines], P):
                out.append(lines)
            if limit and len(out) >= limit:
                break
    return out


def cmd_n19(args):
    av4, fastcanon, _ = dk()
    S = n19_sys()
    pts, n = 19, 38
    gamma = [g for g in S.gamma() if tuple(g) != tuple(range(pts))]
    random.Random(1).shuffle(gamma)
    point_labels = gamma[:args.labels]
    t0 = time.time()
    models = enumerate_models(S, point_labels)
    canon = {}
    for lines in models:
        canon.setdefault(str(fastcanon.canon(pts, [tuple(l) for l in lines])), lines)
    print(f"proposer: {len(models)} labelled models, {len(canon)} types, {time.time() - t0:.0f} s", flush=True)
    full = lambda l: list(l) + list(range(pts, n))
    swaps = []
    for L in range(pts - 1):
        a = list(range(n)); a[pts + L], a[pts + L + 1] = a[pts + L + 1], a[pts + L]
        swaps.append(a)
    labels = swaps + [full(l) for l in point_labels]
    cert = {"type": "v4listed", "n": n, "models": [witness(pts, l) for l in models],
            "reps": [rep(pts, l, S.perms) for l in canon.values()], "labels": labels}
    stmt = statement(pts, S.perms, len(canon))
    out = Path(args.out); out.mkdir(parents=True, exist_ok=True)
    (out / "n19-claim.json").write_text(json.dumps(stmt), encoding="utf-8")
    (out / "n19-cert.json").write_text(json.dumps(cert), encoding="utf-8")
    t0 = time.time()
    cnf = subprocess.run([str(RUNNER), "v4listcnf", str(out / "n19-claim.json"), str(out / "n19-cert.json")],
                         capture_output=True, text=True, encoding="utf-8")
    if cnf.returncode != 0:
        raise SystemExit(cnf.stderr)
    (out / "n19.cnf").write_text(cnf.stdout, encoding="utf-8", newline="\n")
    head = next(l for l in cnf.stdout.splitlines() if l.startswith("p cnf"))
    print(f"Lean CNF: {head} ({time.time() - t0:.0f} s)", flush=True)
    t0 = time.time()
    r = subprocess.run([str(CADICAL), "--lrat=true", "--binary=false", "-q", "n19.cnf", "n19.lrat"], cwd=out,
                       capture_output=True, text=True)
    print(f"cadical rc {r.returncode} ({time.time() - t0:.0f} s), proof {(out / 'n19.lrat').stat().st_size} bytes",
          flush=True)
    if r.returncode != 20:
        raise SystemExit("not refuted: the proposer missed a model")
    cert["proof"] = (out / "n19.lrat").read_text(encoding="utf-8")
    t0 = time.time()
    verdict = run([dict(stmt, key=1, scope=[n], certificate=cert)])[1]
    print(f"GP: held={verdict['held']} reach={verdict['reach']} ({time.time() - t0:.0f} s)")
    (out / "n19-verdict.json").write_text(json.dumps(verdict), encoding="utf-8")


def cmd_difftest19(args):
    """GP's membership verdict against DK's fences on n = 19 V4-invariant structures, fence-valid or not."""
    av4, _, _ = dk()
    S = n19_sys()
    sample = enumerate_models(S, [], fences=False, sort_lines=True, limit=args.limit, seed=args.seed)
    structures = [(l, S.perms) for l in sample]
    got = run(member_claims(19, S.perms, None, structures))
    bad, valid = 0, 0
    for t, (lines, perms) in enumerate(structures):
        expect = not av4.necessary_conditions(19, [frozenset(l) for l in lines], perms)
        valid += expect
        if got[t + 1]["held"] != expect:
            bad += 1
            print("MISMATCH", t, "DK fence-valid" if expect else "DK fence-invalid", "GP held" if got[t + 1]["held"] else "GP refused")
    print(f"difftest19: {len(structures)} structures ({valid} fence-valid), {bad} mismatches")
    return bad


def load_cells():
    """Each nonempty cell's types in that cell's own labelling, keyed by cell name."""
    cells = {}
    for d in sorted(STAGE.iterdir()):
        types = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((d / "types").glob("*.json"))]
        if types:
            cells[types[0]["cell"]] = types
    return cells


def cmd_difftest23(args):
    """Labelled n = 23 types against every cell's statement: held exactly in the cell whose labelling
    they carry (DK's staging), refused in every other."""
    cells = load_cells()
    rnd = random.Random(args.seed)
    pool = [(c, t) for c, ts in cells.items() for t in ts]
    sample = pool if args.limit is None else rnd.sample(pool, args.limit)
    bad = total = 0
    for c, ts in cells.items():
        meta, a0 = ts[0]["cellmeta"], ts[0]["perms"]
        got = run(member_claims(23, a0, meta["bstar"], [(t["lines"], t["perms"]) for _, t in sample]))
        for i, (home, t) in enumerate(sample):
            expect = home == c
            total += 1
            if got[i + 1]["held"] != expect:
                bad += 1
                print("MISMATCH", t["digest"][:16], "home", home, "tested", c, "expected", expect)
    print(f"difftest23: {total} (labelled type, cell) pairs, {bad} mismatches")
    return bad


def cmd_cells(args):
    """The six n = 23 cell counts, each under its catalog premise (CELL-COMPLETE)."""
    cells = load_cells()
    claims = []
    for key, (c, members) in enumerate(cells.items(), 1):
        meta = members[0]["cellmeta"]
        a0 = members[0]["perms"]
        reps = [rep(23, p["lines"], p["perms"]) for p in members]
        stmt = statement(23, a0, len(members), meta["bstar"], catalog=[r["witness"] for r in reps])
        claims.append(dict(stmt, key=key, scope=[46], certificate={"type": "v4catalog", "n": 46, "reps": reps}))
    t0 = time.time()
    got = run(claims)
    for key, c in enumerate(cells, 1):
        print(c, "count", claims[key - 1]["count"], "held", got[key]["held"], flush=True)
    print(f"({time.time() - t0:.0f} s)")
    Path(args.out).mkdir(parents=True, exist_ok=True)
    (Path(args.out) / "cells-verdict.json").write_text(json.dumps(
        {c: {"count": claims[k - 1]["count"], "held": got[k]["held"]} for k, c in enumerate(cells, 1)}, indent=1),
        encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("n19"); a.add_argument("--labels", type=int, default=200); a.add_argument("--out", required=True)
    a = sub.add_parser("difftest19"); a.add_argument("--limit", type=int, default=300); a.add_argument("--seed", type=int, default=1)
    a = sub.add_parser("difftest23"); a.add_argument("--limit", type=int); a.add_argument("--seed", type=int, default=1)
    a = sub.add_parser("cells"); a.add_argument("--out", required=True)
    args = ap.parse_args()
    r = {"n19": cmd_n19, "difftest19": cmd_difftest19, "difftest23": cmd_difftest23, "cells": cmd_cells}[args.cmd](args)
    sys.exit(1 if r else 0)


if __name__ == "__main__":
    main()
