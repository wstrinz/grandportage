PINS = HARVEST / "artifacts/v4-cell-census-v1/output/types"
# Per-cell labelled types: DK's census staging, regenerated by the builder from v4census.py (its
# merge equals the committed pins). A type found in two cells carries a different action in each.
STAGE = HARVEST / "stage"
